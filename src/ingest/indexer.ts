import fs from 'node:fs/promises';
import path from 'node:path';
import { and, eq, isNull, like, sql } from 'drizzle-orm';
import type { Db } from '../db/client.js';
import { contentItems, COLLECTIONS, type Collection, type ContentItem } from '../db/schema.js';
import { extractMetadata, sha256File, titleFromFilename } from './extract.js';
import { isIgnoredName, isIgnoredRelPath, toAbsPath, toRelPath, type CollectionRoots } from './paths.js';

export type Source = 'upload' | 'watcher' | 'scan';

export interface MetadataOverrides {
    title?: string | undefined;
    author?: string | null | undefined;
    description?: string | null | undefined;
    categories?: string[] | undefined;
}

export type IndexResult =
    | { status: 'created' | 'updated' | 'revived' | 'unchanged'; item: ContentItem }
    | { status: 'missing' | 'ignored' };

export interface ReconcileStats {
    scanned: number;
    created: number;
    updated: number;
    revived: number;
    deleted: number;
    failed: number;
}

const nextChangeSeq = sql<number>`nextval('content_change_seq')`;

function escapeLike(s: string): string {
    return s.replace(/[\\%_]/g, m => '\\' + m);
}

/** Library books get their folder names as default categories: books/science/physics/x.epub -> [science, physics]. */
function defaultCategories(collection: Collection, rel: string): string[] {
    if (collection !== 'library') return [];
    return rel.split('/').slice(0, -1).map(s => s.trim().toLowerCase()).filter(Boolean);
}

function cleanCategories(list: string[]): string[] {
    return [...new Set(list.map(c => c.trim().toLowerCase()).filter(Boolean))];
}

/**
 * Keeps content_items in step with the files on disk. Every entry point
 * (upload API, folder watcher, startup scan) goes through here, so metadata
 * is never generated by hand.
 */
export class Indexer {
    private locks = new Map<string, Promise<unknown>>();

    constructor(
        private db: Db,
        readonly roots: CollectionRoots,
        private ffprobePath: string,
    ) {}

    /** Serialises work on the same file so the watcher and an upload never race. */
    private withLock<T>(key: string, fn: () => Promise<T>): Promise<T> {
        const prev = this.locks.get(key) ?? Promise.resolve();
        const run = prev.catch(() => {}).then(fn);
        this.locks.set(key, run);
        void run.catch(() => {}).finally(() => {
            if (this.locks.get(key) === run) this.locks.delete(key);
        });
        return run;
    }

    async ensureRoots() {
        for (const root of Object.values(this.roots)) await fs.mkdir(root, { recursive: true });
    }

    indexFile(
        collection: Collection,
        rel: string,
        opts: { source: Source; overrides?: MetadataOverrides } = { source: 'scan' },
    ): Promise<IndexResult> {
        return this.withLock(`${collection}:${rel}`, () => this.indexFileUnlocked(collection, rel, opts));
    }

    private async indexFileUnlocked(
        collection: Collection,
        rel: string,
        { source, overrides }: { source: Source; overrides?: MetadataOverrides },
    ): Promise<IndexResult> {
        if (isIgnoredRelPath(rel)) return { status: 'ignored' };
        const abs = toAbsPath(this.roots[collection], rel);

        const stat = await fs.stat(abs).catch(() => null);
        if (!stat?.isFile()) {
            await this.markDeletedUnlocked(collection, rel);
            return { status: 'missing' };
        }
        const mtime = new Date(Math.floor(stat.mtimeMs));

        const [existing] = await this.db
            .select()
            .from(contentItems)
            .where(and(eq(contentItems.collection, collection), eq(contentItems.path, rel)));
        const live = existing && !existing.deletedAt ? existing : undefined;

        // Cheap path for rescans: same size and mtime means same file.
        if (live && !overrides && live.size === stat.size && live.fileMtime.getTime() === mtime.getTime()) {
            return { status: 'unchanged', item: live };
        }

        const sha256 = await sha256File(abs);
        if (live && !overrides && live.sha256 === sha256) {
            // Touched but identical (e.g. re-uploaded same file): record mtime, don't notify devices.
            const [item] = await this.db
                .update(contentItems)
                .set({ fileMtime: mtime, size: stat.size, updatedAt: new Date() })
                .where(eq(contentItems.id, live.id))
                .returning();
            return { status: 'unchanged', item: item! };
        }

        const fileChanged = !existing || existing.sha256 !== sha256;
        const extracted =
            fileChanged || !existing
                ? await extractMetadata(abs, stat.size, this.ffprobePath)
                : {
                      mime: existing.mime,
                      extension: existing.extension,
                      title: null,
                      author: existing.author,
                      pages: existing.pages,
                      durationSeconds: existing.durationSeconds,
                  };

        // Admin-edited fields survive rescans; otherwise refresh from the file.
        const keepEdited = Boolean(existing?.editedAt);
        let title = keepEdited ? existing!.title : (extracted.title ?? existing?.title ?? titleFromFilename(rel));
        let author = keepEdited ? existing!.author : (extracted.author ?? existing?.author ?? null);
        let description = existing?.description ?? null;
        let categories = keepEdited ? existing!.categories : defaultCategories(collection, rel);
        let editedAt = existing?.editedAt ?? null;

        if (overrides) {
            if (overrides.title !== undefined) title = overrides.title;
            if (overrides.author !== undefined) author = overrides.author;
            if (overrides.description !== undefined) description = overrides.description;
            if (overrides.categories !== undefined) categories = cleanCategories(overrides.categories);
            if (Object.values(overrides).some(v => v !== undefined)) editedAt = new Date();
        }

        const values = {
            collection,
            path: rel,
            title,
            author,
            description,
            categories,
            mime: extracted.mime,
            extension: extracted.extension,
            size: stat.size,
            sha256,
            pages: extracted.pages,
            durationSeconds: extracted.durationSeconds,
            fileMtime: mtime,
            source,
            version: existing ? existing.version + (fileChanged ? 1 : 0) : 1,
            changeSeq: nextChangeSeq,
            editedAt,
            deletedAt: null,
            updatedAt: new Date(),
        };
        const { collection: _c, path: _p, ...updateSet } = values;
        const [item] = await this.db
            .insert(contentItems)
            .values(values)
            .onConflictDoUpdate({ target: [contentItems.collection, contentItems.path], set: updateSet })
            .returning();

        const status = !existing ? 'created' : existing.deletedAt ? 'revived' : 'updated';
        console.log(`[index] ${status} ${collection}/${rel} (v${item!.version}, ${source})`);
        return { status, item: item! };
    }

    markDeleted(collection: Collection, rel: string): Promise<number> {
        return this.withLock(`${collection}:${rel}`, () => this.markDeletedUnlocked(collection, rel));
    }

    private async markDeletedUnlocked(collection: Collection, rel: string): Promise<number> {
        const rows = await this.db
            .update(contentItems)
            .set({ deletedAt: new Date(), updatedAt: new Date(), changeSeq: nextChangeSeq })
            .where(and(eq(contentItems.collection, collection), eq(contentItems.path, rel), isNull(contentItems.deletedAt)))
            .returning({ id: contentItems.id });
        if (rows.length) console.log(`[index] deleted ${collection}/${rel}`);
        return rows.length;
    }

    /** A whole folder disappeared. */
    async markDeletedUnder(collection: Collection, relDir: string): Promise<number> {
        const rows = await this.db
            .update(contentItems)
            .set({ deletedAt: new Date(), updatedAt: new Date(), changeSeq: nextChangeSeq })
            .where(
                and(
                    eq(contentItems.collection, collection),
                    like(contentItems.path, `${escapeLike(relDir)}/%`),
                    isNull(contentItems.deletedAt),
                ),
            )
            .returning({ id: contentItems.id });
        if (rows.length) console.log(`[index] deleted ${rows.length} item(s) under ${collection}/${relDir}/`);
        return rows.length;
    }

    /** Metadata-only edit from the admin API. */
    async updateMetadata(id: number, patch: MetadataOverrides): Promise<ContentItem | null> {
        const set: Partial<typeof contentItems.$inferInsert> = {};
        if (patch.title !== undefined) set.title = patch.title;
        if (patch.author !== undefined) set.author = patch.author;
        if (patch.description !== undefined) set.description = patch.description;
        if (patch.categories !== undefined) set.categories = cleanCategories(patch.categories);
        const [item] = await this.db
            .update(contentItems)
            .set({ ...set, editedAt: new Date(), updatedAt: new Date(), changeSeq: nextChangeSeq })
            .where(and(eq(contentItems.id, id), isNull(contentItems.deletedAt)))
            .returning();
        return item ?? null;
    }

    private async *walk(dir: string): AsyncGenerator<string> {
        const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
        for (const entry of entries) {
            if (isIgnoredName(entry.name)) continue;
            const full = path.join(dir, entry.name);
            if (entry.isDirectory()) yield* this.walk(full);
            else if (entry.isFile()) yield full;
        }
    }

    /** Full scan: index every file on disk and soft-delete rows whose file is gone. */
    async reconcile(): Promise<ReconcileStats> {
        const stats: ReconcileStats = { scanned: 0, created: 0, updated: 0, revived: 0, deleted: 0, failed: 0 };
        await this.ensureRoots();
        for (const collection of COLLECTIONS) {
            const root = this.roots[collection];
            const seen = new Set<string>();
            for await (const abs of this.walk(root)) {
                const rel = toRelPath(root, abs);
                seen.add(rel);
                stats.scanned++;
                try {
                    const r = await this.indexFile(collection, rel, { source: 'scan' });
                    if (r.status === 'created' || r.status === 'updated' || r.status === 'revived') stats[r.status]++;
                } catch (err) {
                    stats.failed++;
                    console.error(`[index] failed ${collection}/${rel}:`, err);
                }
            }
            const live = await this.db
                .select({ path: contentItems.path })
                .from(contentItems)
                .where(and(eq(contentItems.collection, collection), isNull(contentItems.deletedAt)));
            for (const row of live) {
                if (!seen.has(row.path)) stats.deleted += await this.markDeleted(collection, row.path);
            }
        }
        return stats;
    }
}
